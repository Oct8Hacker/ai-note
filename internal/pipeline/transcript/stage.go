package transcript

import (
	"context"

	"ainote/internal/pipeline"
	"ainote/internal/youtube"
)

// YouTubeAPI provides the metadata and caption track used by this stage.
type YouTubeAPI interface {
	Metadata(context.Context, string) (youtube.Metadata, error)
	Captions(context.Context, string, string, bool) ([]byte, error)
}

// Stage reads captions for videos within the configured duration limit.
type Stage struct {
	YT              YouTubeAPI
	MaxVideoSeconds int
}

var _ pipeline.Stage = (*Stage)(nil)

// Name identifies the worker status for this stage.
func (*Stage) Name() pipeline.Status { return pipeline.StatusTranscribing }

// Run records metadata and returns a cleaned transcript for the worker to checkpoint.
func (s *Stage) Run(ctx context.Context, job *pipeline.Job, deps pipeline.Deps) (pipeline.StageResult, error) {
	var empty pipeline.StageResult
	metadata, err := s.YT.Metadata(ctx, job.VideoID)
	if err != nil {
		return empty, err
	}
	if err := deps.Store.SetVideoMeta(ctx, job.ID, metadata.Title, metadata.DurationSec); err != nil {
		return empty, err
	}
	deps.Progress(50)
	if metadata.DurationSec > s.MaxVideoSeconds {
		return empty, &pipeline.FatalError{Code: "VIDEO_TOO_LONG", Msg: "Video exceeds the configured duration limit."}
	}
	lang, auto, ok := PickLanguage(metadata)
	if !ok {
		return empty, &pipeline.FatalError{Code: "NO_TRANSCRIPT", Msg: "No caption track is available."}
	}
	captions, err := s.YT.Captions(ctx, job.VideoID, lang, auto)
	if err != nil {
		return empty, err
	}
	segments, err := ParseJSON3(captions)
	if err != nil {
		return empty, err
	}
	segments = Clean(segments)
	if len(segments) == 0 {
		return empty, &pipeline.FatalError{Code: "NO_TRANSCRIPT", Msg: "The caption track contains no spoken text."}
	}
	return pipeline.StageResult{
		ArtifactKind: "transcript", Artifact: pipeline.Transcript{Language: lang, AutoGenerated: auto, Segments: segments},
		VideoTitle: &metadata.Title, DurationSec: &metadata.DurationSec,
	}, nil
}
