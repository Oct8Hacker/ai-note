package transcript

import (
	"ainote/internal/pipeline"
	"ainote/internal/pipeline/pipelinetest"
	"ainote/internal/youtube"
	"context"
	"github.com/google/uuid"
	"github.com/stretchr/testify/require"
	"testing"
)

type fakeYT struct {
	meta  youtube.Metadata
	err   error
	body  string
	calls int
	lang  string
	auto  bool
}

func (f *fakeYT) Metadata(context.Context, string) (youtube.Metadata, error) { return f.meta, f.err }
func (f *fakeYT) Captions(_ context.Context, _ string, lang string, auto bool) ([]byte, error) {
	f.calls++
	f.lang = lang
	f.auto = auto
	return []byte(f.body), nil
}
func TestTooLongRejectedBeforeCaptions(t *testing.T) {
	for _, duration := range []int{1200, 1201} {
		yt := &fakeYT{meta: youtube.Metadata{Title: "Lecture", DurationSec: duration, AutoCaptions: langs("hi")}, body: `{"events":[{"dDurationMs":2500,"segs":[{"utf8":"hello"}]}]}`}
		store := pipelinetest.NewMemStore()
		job := &pipeline.Job{ID: uuid.New(), VideoID: "dQw4w9WgXcQ"}
		s := Stage{YT: yt, MaxVideoSeconds: 1200}
		require.Equal(t, pipeline.StatusTranscribing, s.Name())
		got, err := s.Run(context.Background(), job, pipelinetest.TestDeps(store))
		require.Equal(t, duration, store.Job(job.ID).DurationSec)
		require.Equal(t, "Lecture", store.Job(job.ID).VideoTitle)
		if duration > 1200 {
			require.Equal(t, "VIDEO_TOO_LONG", pipeline.ErrorCode(err))
			require.Equal(t, pipeline.ClassFatal, pipeline.Classify(err))
			require.Zero(t, yt.calls)
			continue
		}
		require.NoError(t, err)
		require.Equal(t, 1, yt.calls)
		require.Equal(t, "hi", yt.lang)
		require.True(t, yt.auto)
		require.Equal(t, "transcript", got.ArtifactKind)
		require.Equal(t, pipeline.Transcript{Language: "hi", AutoGenerated: true, Segments: []pipeline.Segment{{EndSec: 2.5, Text: "hello"}}}, got.Artifact)
		require.Equal(t, "Lecture", *got.VideoTitle)
		require.Equal(t, 1200, *got.DurationSec)
		require.Contains(t, store.Progress(), 50)
	}
}
func TestNoCaptions(t *testing.T) {
	for _, available := range []bool{false, true} {
		yt := &fakeYT{body: `{"events":[{"segs":[{"utf8":"[Music]"}]}]}`}
		if available {
			yt.meta.Subtitles = langs("en")
		}
		s := Stage{YT: yt, MaxVideoSeconds: 1200}
		_, err := s.Run(context.Background(), &pipeline.Job{}, pipelinetest.TestDeps(pipelinetest.NewMemStore()))
		require.Equal(t, "NO_TRANSCRIPT", pipeline.ErrorCode(err))
		require.Equal(t, pipeline.ClassFatal, pipeline.Classify(err))
		require.Equal(t, available, yt.calls == 1)
	}
}
func TestUnavailablePropagatesRetryable(t *testing.T) {
	failure := &pipeline.RetryableError{Code: "VIDEO_UNAVAILABLE"}
	yt := &fakeYT{err: failure}
	s := Stage{YT: yt, MaxVideoSeconds: 1200}
	_, err := s.Run(context.Background(), &pipeline.Job{}, pipelinetest.TestDeps(pipelinetest.NewMemStore()))
	require.ErrorIs(t, err, failure)
	require.Zero(t, yt.calls)
}
