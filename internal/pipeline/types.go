// Package pipeline holds the shared contracts between the API/worker runtime
// and the pipeline stages.
package pipeline

import (
	"time"

	"github.com/google/uuid"
)

// Status is a job lifecycle state; stage statuses double as stage names.
type Status string

// Job lifecycle statuses; TRANSCRIBING through PUBLISHING double as stage names.
const (
	StatusQueued                Status = "QUEUED"
	StatusTranscribing          Status = "TRANSCRIBING"
	StatusSummarizing           Status = "SUMMARIZING"
	StatusExtractingFrames      Status = "EXTRACTING_FRAMES"
	StatusPublishing            Status = "PUBLISHING"
	StatusCompleted             Status = "COMPLETED"
	StatusCompletedWithWarnings Status = "COMPLETED_WITH_WARNINGS"
	StatusFailed                Status = "FAILED"
	StatusDeadLettered          Status = "DEAD_LETTERED"
)

// IsTerminal reports whether no further processing happens in this status.
func (s Status) IsTerminal() bool {
	switch s {
	case StatusCompleted, StatusCompletedWithWarnings, StatusFailed, StatusDeadLettered:
		return true
	}
	return false
}

// NextStage returns the stage following s; false after PUBLISHING or for non-stage statuses.
func (s Status) NextStage() (Status, bool) {
	switch s {
	case StatusQueued:
		return StatusTranscribing, true
	case StatusTranscribing:
		return StatusSummarizing, true
	case StatusSummarizing:
		return StatusExtractingFrames, true
	case StatusExtractingFrames:
		return StatusPublishing, true
	}
	return "", false
}

// Job is the persisted state of one video-to-notes job.
type Job struct {
	ID          uuid.UUID
	VideoID     string
	YouTubeURL  string
	Status      Status
	VideoTitle  string
	DurationSec int

	NotionParentID       string
	NotionResolvedParent string
	NotionParentKind     string // "page" | "data_source"
	NotionTitleProp      string

	NotionPageID          string
	NotionPageURL         string
	NotionCreateStartedAt *time.Time
	Attempts              int
}

// Segment is one timed span of transcript text.
type Segment struct {
	StartSec float64 `json:"start_sec"`
	EndSec   float64 `json:"end_sec"`
	Text     string  `json:"text"`
}

// Transcript is the TRANSCRIBING stage output.
type Transcript struct {
	Language      string    `json:"language"`
	AutoGenerated bool      `json:"auto_generated"`
	Segments      []Segment `json:"segments"`
}

// Section is one headed group of bullets in the synthesized notes.
type Section struct {
	Heading  string   `json:"heading"`
	StartSec float64  `json:"start_sec"`
	EndSec   float64  `json:"end_sec"`
	Bullets  []string `json:"bullets"`
}

// Visual is an LLM-requested frame capture tied to a section.
type Visual struct {
	TimestampSec float64 `json:"timestamp_sec"`
	SectionIndex int     `json:"section_index"`
	Caption      string  `json:"caption"`
	Reason       string  `json:"reason"`
	Priority     int     `json:"priority"`
}

// Synthesis is the LLM output, schema per SRS section 11.2.
type Synthesis struct {
	Title    string    `json:"title"`
	Overview string    `json:"overview"`
	Sections []Section `json:"sections"`
	Visuals  []Visual  `json:"visuals"`
}

// FrameStatus is "pending" | "captured" | "failed" | "omitted".
type FrameStatus string

// Frame tracks one requested screenshot through capture, verification and upload.
type Frame struct {
	JobID              uuid.UUID
	Idx                int
	RequestedSec       float64
	CapturedSec        *float64
	SectionIndex       int
	Caption, Reason    string
	Status             FrameStatus
	Verified           bool
	ImageJPEG          []byte
	NotionFileUploadID string
	NotionUploadedAt   *time.Time
	WarningCode        string
}

// Warning is a non-fatal issue surfaced with a completed job.
type Warning struct {
	Code         string   `json:"code"`
	TimestampSec *float64 `json:"timestamp_sec,omitempty"`
}

// Warning codes, SRS section 6.6.
const (
	WarnFrameExtractionFailed = "FRAME_EXTRACTION_FAILED"
	WarnFrameNotRelevant      = "FRAME_NOT_RELEVANT"
	WarnVisualDroppedInvalid  = "VISUAL_DROPPED_INVALID"
	WarnFrameVerifySkipped    = "FRAME_VERIFY_SKIPPED"
)
